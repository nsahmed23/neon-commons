    if executor.mode=='native_local_opentofu_only':
        before=document.get('output_changes',{}).get('fixture',{}).get('before')
        if digest(before)!=request['bindings']['before_value_sha256']:_fail('review_binding_changed')
        reviewed=_review_native_output_plan(document,executor,reviewed,bound_before=before)
    summary={'status':reviewed['status'],'plan_json_sha256':reviewed['plan_json_sha256'],
             'generic_review_status':reviewed.get('generic_review_status',reviewed['status']),'generic_blockers':reviewed['blockers']}
    if request['review']!=summary:_fail('review_binding_changed')
    return request


