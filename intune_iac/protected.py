def _review_native_output_plan(document, executor, generic_review, *, bound_before=_SECRET):
    """Strict local-output slice using independently observed pre-plan state.

    OpenTofu 1.10 refresh recalculates prior_state output values. Keep the raw
    generic review diagnostic; never edit the plan to manufacture consistency.
    """
    allowed={'format_version','terraform_version','planned_values','output_changes','prior_state','configuration','timestamp','errored','resource_changes'}
    if set(document)-allowed or document.get('format_version')!='1.2' or document.get('terraform_version')!=_engine_version(executor) or document.get('errored')is not False or document.get('resource_changes',[])!=[]:_fail('native_output_plan_shape')
    planned=document.get('planned_values',{})
    if set(planned)!={'outputs','root_module'} or planned['root_module']!={} or set(planned['outputs'])!={'fixture'}:_fail('native_output_plan_shape')
    expected=load_json(executor.root/'work/main.tf.json')['output']['fixture']['value']
    state=load_json(executor.root/'work/state/terraform.tfstate')
    before=state['outputs']['fixture']['value'] if bound_before is _SECRET else bound_before
    change=document.get('output_changes',{}).get('fixture')
    if set(document.get('output_changes',{}))!={'fixture'} or type(change)is not dict or set(change)!={'actions','before','after','after_unknown','before_sensitive','after_sensitive'}:_fail('native_output_plan_shape')
    action=['no-op'] if canonical(before)==canonical(expected) else ['update']
    if change!={'actions':action,'before':before,'after':expected,'after_unknown':False,'before_sensitive':False,'after_sensitive':False}:_fail('native_output_plan_mismatch')
    if document['configuration']!={'root_module':{'outputs':{'fixture':{'expression':{'constant_value':expected}}}}}:_fail('native_configuration_mismatch')
    output=planned['outputs']['fixture']
    if set(output)!={'value','sensitive','type'} or output['sensitive']is not False or canonical(output['value'])!=canonical(expected):_fail('native_output_plan_mismatch')
    prior=document.get('prior_state',{})
    if set(prior)!={'format_version','terraform_version','values'} or prior['format_version']!='1.0' or prior['terraform_version']!=_engine_version(executor) or set(prior['values'])!={'root_module','outputs'} or prior['values']['root_module']!={} or set(prior['values']['outputs'])!={'fixture'}:_fail('native_output_plan_shape')
    # No generic blockers other than the independently explained output mismatch.
    if any(issue['code']!='prior_output_value_mismatch' for issue in generic_review['blockers']):_fail('native_output_plan_review')
    return dict(generic_review,status='no_change' if action==['no-op'] else 'changes_require_review',
                generic_review_status=generic_review['status'],assurance='native_local_output_slice_with_independent_state')


