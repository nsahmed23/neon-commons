def _now(): return int(time.time())


def _fail(code): raise AppError(code, 'Protected local operation could not be verified.')


def _path(value):
    if not isinstance(value, (str, os.PathLike)) or not str(value) or '\x00' in str(value): _fail('invalid_path')
    path = Path(value).absolute()
    if any(p.is_symlink() for p in (path, *path.parents)): _fail('unsafe_path')
    return path.resolve()


def _json_snapshot(value):
    # Bound Python inputs before serialization, including cyclic containers.
    pending=[(value,0)]; nodes=0
    while pending:
        item, depth=pending.pop(); nodes+=1
        if depth>32 or nodes>10000: _fail('invalid_document')
        if type(item) is dict:
            if len(item)>2048 or any(type(k)is not str or len(k)>512 for k in item): _fail('invalid_document')
            pending.extend((v,depth+1) for v in item.values())
        elif type(item) is list: pending.extend((v,depth+1) for v in item)
        elif item is not None and type(item) not in (str,int,bool,float): _fail('invalid_document')
        if type(item)is str and ('${' in item or '%{' in item): _fail('configuration_interpolation_unsupported')
    data=canonical(value)
    if len(data)>1024*1024: _fail('invalid_document')
    return parse_json(data)


def _sync(path):
    fd=os.open(path,os.O_RDONLY | getattr(os,'O_DIRECTORY',0))
    try: os.fsync(fd)
    finally: os.close(fd)


def _exclusive(path, data, mode=0o600):
    path=_path(path)
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL|getattr(os,'O_NOFOLLOW',0),mode)
    with os.fdopen(fd,'wb') as out: out.write(data); out.flush(); os.fsync(out.fileno())
    _sync(path.parent)


def _sha(path, *, max_bytes=256*1024*1024):
    path=_path(path); h=hashlib.sha256(); total=0
    fd=os.open(path,os.O_RDONLY|getattr(os,'O_NOFOLLOW',0)|getattr(os,'O_NONBLOCK',0))
    with os.fdopen(fd,'rb') as stream:
        if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode): _fail('invalid_file')
        while True:
            chunk=stream.read(1024*1024)
            if not chunk: break
            total+=len(chunk)
            if total>max_bytes: _fail('input_too_large')
            h.update(chunk)
    return h.hexdigest()


def _native_profile(executable, executable_sha):
    profile = OPENTOFU_PINS.get(executable_sha)
    if profile is None or Path(executable).stat().st_size != profile['bytes']:
        _fail('unqualified_executable')
    return profile


