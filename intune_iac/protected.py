def read_native_operation(operation_id, state_dir):
    unknown={'status':'unknown','execution_authorized':False,'events':[]}
    try:
        if type(operation_id)is not str or not _ID.fullmatch(operation_id):return unknown
        root=_path(state_dir)/operation_id
        paths=[]
        for index,path in enumerate(root.iterdir()):
            if index>=5:return unknown
            paths.append(path)
        paths.sort()
        if not paths or len(paths)>5 or [p.name for p in paths]!=[f'{i:02d}.json' for i in range(len(paths))]:return unknown
        previous='0'*64;events=[];request=None
        for index,path in enumerate(paths):
            value=load_json(_path(path))
            if type(value)is not dict or set(value)!={'schema_version','sequence','kind','previous_sha256','payload'} or value['schema_version']!=VERSION or type(value['sequence'])is not int or value['sequence']!=index or value['kind']!=_EVENT_KINDS[index] or value['previous_sha256']!=previous:return unknown
            payload=value['payload']
            if index==0:
                if type(payload)is not dict or set(payload)!={'request'}:return unknown
                request=payload['request'];_request_shape(request)
                if type(request)is not dict or set(request)!=_REQUEST_KEYS or request['operation_id']!=operation_id or request['binding_sha256']!=digest(request['bindings']):return unknown
            elif index==1:
                if payload!={'request_sha256':digest(request),'scope':'local_fixture_only'}:return unknown
            elif index==2:
                if payload!={'binding_sha256':request['binding_sha256']}:return unknown
            elif index==3:
                if type(payload)is not dict or set(payload)!={'state_sha256','value_sha256','serial','lineage_sha256'} or not _desired_readback(request,payload) or not re.fullmatch('[0-9a-f]{64}',payload['state_sha256']):return unknown
            elif payload!={'outcome':'succeeded_verified','request_sha256':digest(request)}:return unknown
            events.append(value);previous=_sha(path)
        return {'status':'succeeded_verified' if len(events)==5 else 'outcome_unknown','execution_authorized':False,'request':request,'events':events,'receipt_sha256':previous}
    except Exception:return unknown


def reconcile_native_operation(operation_id, state_dir, *, executor):
    result={'classification':'unknown','replay_authorized':False,'execution_authorized':False}
    try:
        history=read_native_operation(operation_id,state_dir)
        if 'request' not in history:return result
        request=_validate_request(history['request'],executor,fresh=False,state=False)
        state=_state(executor)
        classification='desired_state_observed' if _desired_readback(request,state) else 'matches_precondition' if state['state_sha256']==request['bindings']['before_state_sha256'] else 'diverged'
        result.update(classification=classification,state_sha256=state['state_sha256'],value_sha256=state['value_sha256'])
    except Exception:pass
    return result


def _convergence_report(executor, request):
    """Re-derive a local no-change assertion from native plan bytes and state.

    This proves output-only convergence, never that an approved apply occurred.
    Callers must separately reconstruct the operation's execution journal.
    """
    if type(executor)is not NativeLocalExecutor:_fail('wrong_executor_mode')
    request=_validate_request(request,executor,fresh=False,state=False)
    before=_state(executor)
    if not _desired_readback(request,before):_fail('readback_mismatch')
    plan_path=executor.root/'work/second.tfplan'
    plan_sha=_sha(plan_path)
    raw=_run(executor,'second_show')
    if read_bytes(executor.root/'work/second-plan.json')!=raw:_fail('second_plan_json_mismatch')
    document=parse_json(raw);normalized=dict(document);normalized.setdefault('resource_changes',[])
    review=_review_native_output_plan(document,executor,_generic_review(normalized,executor))
    if review['status']!='no_change':_fail('second_plan_has_changes')
    _validate_request(request,executor,fresh=False,state=False)
    after=_state(executor)
    if before!=after or _sha(plan_path)!=plan_sha:_fail('convergence_evidence_changed')
    return {'schema_version':'native-local-convergence/1','status':'verified','changes':[],
            'scope':'native_local_output_only','execution_authorized':False,
            'request_sha256':digest(request),'before_state_sha256':before['state_sha256'],
            'after_state_sha256':after['state_sha256'],'lineage_sha256':after['lineage_sha256'],
            'serial':after['serial'],'value_sha256':after['value_sha256'],
            'approved_saved_plan_sha256':request['bindings']['saved_plan_sha256'],
            'second_plan_sha256':plan_sha,'second_plan_json_sha256':hashlib.sha256(raw).hexdigest()}


def reconstruct_native_convergence(executor, request, report):
    """Validate persisted evidence with native show; never run plan or apply."""
    reconstructed=_convergence_report(executor,request)
    # Python mapping equality equates False with 0 and integers with floats.
    # Durable typed evidence must match JSON semantics, not those coercions.
    if type(report)is not dict or canonical(_json_snapshot(report))!=canonical(reconstructed):_fail('convergence_report_changed')
    return reconstructed


def verify_native_convergence(executor, request):
    """Save a distinct second plan; retain the exact approved original.

    Existing second-plan artifacts are inspected and never overwritten. An
    interrupted successful plan can be completed with its independently derived
    JSON; an incomplete or divergent artifact remains visible and fails closed.
    """
    if type(executor)is not NativeLocalExecutor:_fail('wrong_executor_mode')
    request=_validate_request(request,executor,fresh=False,state=False)
    before=_state(executor)
    if not _desired_readback(request,before):_fail('readback_mismatch')
    lock=executor.root/'.convergence-lock';owner=canonical({'request_sha256':digest(request),'token':uuid.uuid4().hex})
    try:_exclusive(lock,owner)
    except FileExistsError:_fail('target_locked')
    try:
        work=executor.root/'work';plan=work/'second.tfplan';sidecar=work/'second-plan.json'
        if not plan.exists():
            if sidecar.exists():_fail('incomplete_convergence_evidence')
            _run(executor,'second_plan')
            fd=os.open(_path(plan),os.O_RDONLY|getattr(os,'O_NOFOLLOW',0))
            try:os.fsync(fd)
            finally:os.close(fd)
            _sync(work)
        raw=_run(executor,'second_show')
        if not sidecar.exists():_exclusive(sidecar,raw)
        report=_convergence_report(executor,request)
        if before!=_state(executor):_fail('convergence_evidence_changed')
        return report
    finally:
        if read_bytes(lock)!=owner:_fail('ownership_lost')
        lock.unlink();_sync(executor.root)
